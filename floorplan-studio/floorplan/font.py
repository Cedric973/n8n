GLYPH_WIDTH = 4.0   # default box width, in glyph units
GAP = 1.2           # space between boxes

WIDTHS: dict[str, float] = {
    " ": 2.2, "I": 2.0, "M": 5.0, "W": 5.0,
    "i": 2.0, "l": 2.0, "j": 2.4, "f": 3.0, "t": 3.0, "r": 3.2, "m": 5.2, "w": 5.0,
    "'": 1.2, '"': 2.2, ".": 1.6, ",": 1.6, ":": 1.6, "·": 1.6, "-": 3.4, "/": 3.6,
    "(": 3.2, ")": 3.2, "[": 2.8, "]": 2.8, "\u00b2": 2.6,
}


def width(char: str) -> float:
    """Design width of a glyph box, in glyph units."""
    return WIDTHS.get(char, GLYPH_WIDTH)


def natural_width(text: str) -> float:
    """Width of a string laid out at its natural proportions, in glyph units."""
    if not text:
        return 0.0
    return sum(width(c) for c in text) + GAP * (len(text) - 1)


def glyph(char: str) -> list[list[tuple[float, float]]]:
    """Strokes for one character, in glyph units. Unknown characters draw a box."""
    if char in GLYPHS:
        return GLYPHS[char]
    upper = char.upper()
    if upper in GLYPHS:  # an accented capital falls back to its base letter
        return GLYPHS[upper]
    box = width(char)
    return [[(0.3, 0), (box - 0.3, 0), (box - 0.3, 5), (0.3, 5), (0.3, 0)]]
