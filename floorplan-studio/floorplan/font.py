def glyph(char: str) -> list[list[tuple[float, float]]]:
    """Strokes for one character, in glyph units. Unknown characters draw a box."""
    if char in GLYPHS:
        return GLYPHS[char]
    upper = char.upper()
    if upper in GLYPHS:
        strokes = GLYPHS[upper]
        k = X_HEIGHT
        return [[(x, y * k) for x, y in stroke] for stroke in strokes]
    return [[(0.4, 0), (3.6, 0), (3.6, 5), (0.4, 5), (0.4, 0)]]
