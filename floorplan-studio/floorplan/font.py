"""A single-stroke vector font, for rasterising plans without a font library.

Glyphs are polylines on a grid four units wide and ``CAP`` units tall, with the
baseline at y=0 — the same construction as the stick fonts CAD packages have
drafted with for decades. Lowercase is drawn with the uppercase strokes at a
reduced height, which is enough for labels and dimension strings.

This font is used by :mod:`floorplan.raster` only. SVG and PDF output uses real
Helvetica, so a PNG shows different letterforms — but each glyph is advanced and
scaled to the Helvetica width of its character, so a string occupies exactly the
space it will occupy in the real output. That is what makes the preview worth
trusting when checking whether a label fits its room.
"""

